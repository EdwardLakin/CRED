import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'

const source = readFileSync('src/features/reports/export/executive-pdf.ts','utf8')

test('executive PDF does not expose internal approval state or product attribution', () => {
  assert.doesNotMatch(source, /Generated by CRED/)
  assert.doesNotMatch(source, /\.text\(snapshot\.approval\.status/)
  assert.doesNotMatch(source, /sectionHeading\(doc, "Approval"/)
})

test('report completion uses actual completion metadata only', () => {
  assert.match(source, /snapshot\.approval\.reviewedBy\?\.trim\(\)/)
  assert.match(source, /snapshot\.approval\.approvedAt \|\| ""/)
  assert.doesNotMatch(source, /snapshot\.approval\.approvedAt \|\| snapshot\.reportDate/)
  assert.match(source, /sectionHeading\(doc, "Report Completion"/)
})

test('standard item cards retain every attached photo', () => {
  assert.match(source, /const extras = item\.mediaIds\.slice\(1\)/)
  assert.match(source, /for \(let start = 0; start < extras\.length; start \+= 2\)/)
  assert.doesNotMatch(source, /slice\(1, 3\)/)
})

test('PDF honors metadata, timestamps, evidence accent and footer report ID toggles', () => {
  assert.match(source, /style\.captureMetadata \? item\.category : null/)
  assert.match(source, /document\.details\.filter/)
  assert.match(source, /style\.timestamps \|\| !\/captured\|date\|time\/i/)
  assert.match(source, /evidenceAccent/)
  assert.match(source, /branding\.show_report_id\)/)
})

test('section labels cannot degrade into bare section numbers', () => {
  assert.match(source, /const showLabel = style\.showSectionLabels !== false/)
  assert.match(source, /style\.showSectionNumbers && number/)
})

test('no-cover layout reserves the Documented Items heading with its first item', () => {
  assert.match(source, /reserveHeadingWithFirstItem/)
  assert.match(source, /else reserveHeadingWithFirstItem\(doc, snapshot, branding, theme\)/)
})

test('all exposed typography areas have PDF font mappings', () => {
  for (const area of ['cover_page','header','section_headings','body_text','evidence_titles','evidence_notes','footer','signature']) {
    assert.match(source, new RegExp(area))
  }
})
